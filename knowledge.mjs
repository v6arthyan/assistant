export function searchKnowledge(query,mode='client',limit=5) {
 const q=normalize(query);if(!q)return [];
 const words=q.split(' ').filter(w=>!STOP.has(w));
 return entriesForMode(mode).map(entry=>{
  let score=0;const matches=[];
  for(const alias of entry.keys){const key=normalize(alias);if(!key)continue;
   if((' '+q+' ').includes(' '+key+' ')){const n=key.split(' ').length;matches.push(n>1?12+n*2:8);}
   else if(/^[a-z]{5,}$/.test(key)&&words.some(w=>/^[a-z]+$/.test(w)&&near(w,key)))matches.push(4);
  }
  matches.sort((a,b)=>b-a);score=matches.length?matches[0]+matches.slice(1,3).reduce((a,b)=>a+b,0)*0.15:0;
  return {entry,score};
 }).filter(x=>x.score>=4).sort((a,b)=>b.score-a.score||a.entry.id.localeCompare(b.entry.id)).slice(0,Math.max(0,Math.min(limit,8)));
}
