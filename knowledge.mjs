 return String(text??'').normalize('NFKC').toLowerCase().replace(/\b(?:[a-z]\.){2,}[a-z]?\.?/g,match=>match.replace(/\./g,'' )).replace(/[^\p{L}\p{M}\p{N}]+/gu,' ').trim().replace(/\s+/g,' ');
